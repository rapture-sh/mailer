import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { beforeAll, describe, expect, it } from "vitest";
import { build } from "~/build/index";

const fixtures = fileURLToPath(new URL("./fixtures", import.meta.url));

async function into(): Promise<string> {
  const directory = await mkdtemp(join(tmpdir(), "mailer-build-"));

  return join(directory, "templates.ts");
}

const copy = {
  default: "en-GB",
  catalogs: join(fixtures, "locales"),
  values: { supportLink: '<a href="mailto:support@example.com">support@example.com</a>' },
};

async function run(options: { senders?: readonly string[] } = {}) {
  const out = await into();
  const result = await build({ letters: fixtures, out, copy, ...options });
  const module = await readFile(result.out, "utf8");
  const bodies = await readFile(result.bodiesOut, "utf8");

  return { result, module, bodies };
}

describe("build", () => {
  it("should treat a file with a header as a letter and one without as a partial", async () => {
    const { result } = await run();

    expect([result.letters, result.partials]).toEqual([
      ["booking", "feedback", "magic-code", "receipt", "reminder", "welcome"],
      ["layout"],
    ]);
  });

  it("should write the module and say that it did", async () => {
    const { result } = await run();

    expect(result).toMatchObject({ written: true, stale: true });
  });

  it("should write nothing the second time, because nothing changed", async () => {
    const out = await into();

    await build({ letters: fixtures, out, copy });
    const second = await build({ letters: fixtures, out, copy });

    expect(second).toMatchObject({ written: false, stale: false });
  });

  it("should report a stale file without writing it in check mode", async () => {
    const out = await into();

    await writeFile(out, "// out of date\n", "utf8");
    const result = await build({ letters: fixtures, out, copy, check: true });

    expect([result.stale, result.written, await readFile(out, "utf8")]).toEqual([
      true,
      false,
      "// out of date\n",
    ]);
  });
});

describe("the module it writes", () => {
  let module = "";

  beforeAll(async () => {
    module = (await run()).module;
  });

  it("should say it is generated and not to edit it", () => {
    expect(module.split("\n")[0]).toMatch(
      /^\/\/ Generated by the mailer build from .*Do not edit\.$/,
    );
  });

  it("should import defineTemplates and the bodies beside it", () => {
    // Attachment comes with it here because a fixture letter declares one the caller
    // passes, which is a field typed as an Attachment.
    expect(module).toContain(
      'import { type Attachment, defineTemplates } from "@rapture-sh/mailer";',
    );
    expect(module).toContain('import { bodies, files, copy } from "./templates.bodies";');
  });

  it("should read a field off a placeholder in the body", () => {
    expect(module).toContain(
      '"magic-code": { addressed: "caller"; from: "auth"; fields: { code: string } };',
    );
  });

  it("should give a letter with no placeholders no fields", () => {
    expect(module).toContain('"welcome": { addressed: "caller"; fields: Record<never, never> };');
  });

  it("should mark a letter with an inbox as addressed by itself", () => {
    expect(module).toContain(
      '"feedback": { addressed: "inbox"; fields: { from: string; note: string } };',
    );
  });

  it("should write the sender into the type, not only the value", () => {
    expect(module).toContain('"magic-code": { addressed: "caller"; from: "auth";');
    expect(module).toContain('"welcome": { addressed: "caller"; fields: Record<never, never> };');
  });

  it("should read an each block as rows and an if block as optional", () => {
    expect(module).toContain(
      '"booking": { addressed: "caller"; from: "notifications"; fields: { activityName: string; currency: string; participants: number; startsAt: number | Date; tickets: readonly string[]; timezone: string; totalMinor: number; voucherCode?: string } };',
    );
  });

  it("should turn a subject with a placeholder into a function of the fields", () => {
    expect(module).toContain(
      // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source, not a literal
      "subject: (fields) => `Your booking for ${fields.activityName} is confirmed`,",
    );
  });

  it("should resolve a subject written as a copy key through t", () => {
    expect(module).toContain(
      'subject: (fields, { t }) => t("magic-code.subject", { code: fields.code }),',
    );
  });

  it("should require a field the subject's copy key names, whatever the body implied", () => {
    // reminder.hbs asks for activityName only inside an #if, which is inferred optional.
    // Emitted optional, t() here would be handed a string | undefined and the generated
    // module would not compile.
    expect(module).toContain(
      '"reminder": { addressed: "caller"; from: "notifications"; fields: { activityName: string } };',
    );
    expect(module).toContain(
      'subject: (fields, { t }) => t("reminder.subject", { activityName: fields.activityName }),',
    );
  });

  it("should carry the locales and the catalogs", () => {
    expect(module).toContain("export type Locale = keyof typeof copy.catalogs;");
    expect(module).toContain("defineTemplates<Letters, typeof copy>({");
  });

  it("should leave a subject with no placeholder as a string", () => {
    expect(module).toContain('subject: "Welcome to Acme",');
  });

  it("should carry the sender, the inbox and the reply-to field through", () => {
    expect(module).toContain('from: "auth",');
    expect(module).toContain('inbox: "feedback@example.com",');
    expect(module).toContain('replyToField: "from",');
  });

  it("should carry the sample through, so the preview cannot drift from the fields", () => {
    expect(module).toContain('code: "519204",');
  });

  it("should take each body from the compiled module beside it", () => {
    expect(module).toContain('html: bodies["magic-code"],');
  });

  it("should not carry the precompiler's output, or its suppression", () => {
    expect(module).not.toContain("@ts-nocheck");
    expect(module).not.toContain("runtime.template(");
  });
});

describe("the compiled bodies beside it", () => {
  let bodies = "";

  beforeAll(async () => {
    bodies = (await run()).bodies;
  });

  it("should carry the suppression, because a precompiled body cannot pass strict mode", () => {
    expect(bodies.split("\n")[0]).toContain("@ts-nocheck");
  });

  it("should precompile every body rather than ship the source", () => {
    expect(bodies).toContain("runtime.template({");
    expect(bodies).not.toContain("{{#> layout");
  });

  it("should register the partials before any letter can use one", () => {
    expect(bodies.indexOf("registerPartial")).toBeLessThan(bodies.indexOf("export const bodies"));
  });
});

describe("what the build refuses", () => {
  it("should refuse a sender that is not declared", async () => {
    await expect(run({ senders: ["notifications"] })).rejects.toThrow(
      /from: 'auth' is not a sender/,
    );
  });

  it("should accept the senders the letters name", async () => {
    await expect(run({ senders: ["auth", "notifications"] })).resolves.toMatchObject({
      result: { written: true },
    });
  });

  it("should take the letters as a list of files rather than a directory", async () => {
    const out = await into();

    const result = await build({
      letters: [join(fixtures, "welcome.hbs"), join(fixtures, "layout.hbs")],
      out,
      copy,
    });

    expect(result.letters).toEqual(["welcome"]);
  });

  it("should import the package under whatever name it is installed as", async () => {
    const out = await into();

    await build({ letters: fixtures, out, copy, packageImport: "@acme/mail" });

    expect(await readFile(out, "utf8")).toContain(
      'import { type Attachment, defineTemplates } from "@acme/mail";',
    );
  });

  it("should refuse a directory with no letters in it", async () => {
    const empty = await mkdtemp(join(tmpdir(), "mailer-empty-"));

    await expect(build({ letters: empty, out: join(empty, "out.ts") })).rejects.toThrow(
      /no letters found/,
    );
  });

  it("should name the file it could not read", async () => {
    const directory = await mkdtemp(join(tmpdir(), "mailer-bad-"));

    await writeFile(join(directory, "broken.hbs"), "---\nsubject: Hi\n", "utf8");

    await expect(build({ letters: directory, out: join(directory, "out.ts") })).rejects.toThrow(
      /broken\.hbs: the header opens with --- but never closes/,
    );
  });
});

describe("the module as a consumer gets it", () => {
  it("should be exactly what is committed under generated/", async () => {
    // The committed output is typechecked by tsc and rendered by generated.test.ts, so
    // this asserts three things at once: the output is reproducible, it compiles, and it
    // works. A fixture change rewrites it and fails once, the way a snapshot does.
    const result = await build({
      letters: fixtures,
      out: fileURLToPath(new URL("./generated/templates.ts", import.meta.url)),
      copy,
      senders: ["auth", "notifications"],
    });

    expect([result.written, result.stale]).toEqual([false, false]);
  });

  it("should report the keys no letter asked for", async () => {
    const { result } = await run();

    expect(result.unusedKeys).toEqual(["unused.key"]);
  });

  it("should report the locales it read", async () => {
    const { result } = await run();

    expect(result.locales).toEqual(["de-CH", "en-GB", "pirate-Speak"]);
  });
});

describe("a letter's attachments", () => {
  async function letters(header: string, body = "<p>Hi</p>\n") {
    const directory = await mkdtemp(join(tmpdir(), "mailer-attach-"));

    await writeFile(join(directory, "logo.png"), "Acme", "utf8");
    await writeFile(join(directory, "note.hbs"), `---\n${header}\n---\n${body}`, "utf8");

    return { directory, out: join(directory, "templates.ts") };
  }

  async function run(header: string, body?: string) {
    const { directory, out } = await letters(header, body);
    const result = await build({ letters: directory, out });

    return {
      module: await readFile(result.out, "utf8"),
      bodies: await readFile(result.bodiesOut, "utf8"),
    };
  }

  it("should inline a file beside the letter, base64 in the bodies module", async () => {
    const { bodies } = await run("subject: Hi\nattachments:\n  - path: logo.png");

    expect(bodies).toContain('"note/logo.png": "QWNtZQ=="');
  });

  it("should attach it with the content type its extension implies", async () => {
    const { module } = await run("subject: Hi\nattachments:\n  - path: logo.png");

    expect(module).toContain(
      'attachments: () => [{ filename: "logo.png", content: { base64: files["note/logo.png"] }, contentType: "image/png" }]',
    );
  });

  it("should reference a file by content id where the header gave one", async () => {
    const { module } = await run("subject: Hi\nattachments:\n  - path: logo.png\n    cid: logo");

    expect(module).toContain('inline: { cid: "logo" }');
  });

  it("should make an attachment the caller passes a field of the letter", async () => {
    const { module } = await run("subject: Hi\nattachments:\n  - field: invoice");

    expect(module).toContain(
      '"note": { addressed: "caller"; attachments: true; fields: { invoice: Attachment } };',
    );
  });

  it("should make an optional one an optional field", async () => {
    const { module } = await run("subject: Hi\nattachments:\n  - field: terms\n    optional: true");

    expect(module).toContain("fields: { terms?: Attachment }");
    expect(module).toContain("...(fields.terms === undefined ? [] : [fields.terms])");
  });

  it("should ask for no sample value for an attachment, because there is none", async () => {
    const { module } = await run("subject: Hi\nattachments:\n  - field: invoice");

    expect(module).not.toContain("sample:");
  });

  it("should refuse a sample that carries an attachment", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nattachments:\n  - field: invoice\nsample:\n  invoice: a file",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(
      /'invoice', which is an attachment/,
    );
  });

  it("should refuse an attachment that is both a path and a field", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nattachments:\n  - path: logo.png\n    field: invoice",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(/both a path and a field/);
  });

  it("should refuse an attachment that is neither", async () => {
    const { directory, out } = await letters("subject: Hi\nattachments:\n  - filename: x.pdf");

    await expect(build({ letters: directory, out })).rejects.toThrow(/needs a path to a file/);
  });

  it("should refuse a content id on an attachment the caller passes", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nattachments:\n  - field: invoice\n    cid: invoice",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(/the caller sets its cid/);
  });

  it("should refuse an attachment key it does not know, which is usually a typo", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nattachments:\n  - path: logo.png\n    content_type: image/png",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(
      /'content_type' is not an attachment key/,
    );
  });

  it("should refuse a field that the body already renders", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nattachments:\n  - field: invoice\nsample:\n  invoice: x",
      "<p>{{ invoice }}</p>\n",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(
      /'invoice' is already a field of this letter/,
    );
  });

  it("should refuse attachments written as anything but a list", async () => {
    const { directory, out } = await letters("subject: Hi\nattachments: logo.png");

    await expect(build({ letters: directory, out })).rejects.toThrow(
      /attachments has to be a list/,
    );
  });
});

describe("a field name that would not read as a property", () => {
  async function letters(header: string, body: string) {
    const directory = await mkdtemp(join(tmpdir(), "mailer-names-"));

    await writeFile(join(directory, "logo.png"), "Acme", "utf8");
    await writeFile(join(directory, "note.hbs"), `---\n${header}\n---\n${body}`, "utf8");

    return { directory, out: join(directory, "templates.ts") };
  }

  it("should refuse an attachment field that is not an identifier", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nattachments:\n  - field: my-invoice",
      "<p>Hi</p>\n",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(
      /'my-invoice' cannot be the name of a field/,
    );
  });

  it("should refuse one a placeholder named, which handlebars accepts and TypeScript cannot", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nsample:\n  odd-one: x",
      "<p>{{ odd-one }}</p>\n",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(
      /'odd-one' cannot be the name of a field/,
    );
  });

  it("should refuse one the header declared a type for", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nfields:\n  2fa: string\nsample:\n  2fa: x",
      "<p>Hi</p>\n",
    );

    await expect(build({ letters: directory, out })).rejects.toThrow(
      /'2fa' cannot be the name of a field/,
    );
  });

  it("should take a name with an underscore or a digit in it", async () => {
    const { directory, out } = await letters(
      "subject: Hi\nsample:\n  code_2: x",
      "<p>{{ code_2 }}</p>\n",
    );

    const result = await build({ letters: directory, out });

    expect(result.written).toBe(true);
  });
});
