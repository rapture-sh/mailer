import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { beforeAll, describe, expect, it } from "vitest";
import { build } from "~/build/index";

const fixtures = fileURLToPath(new URL("./fixtures", import.meta.url));

async function into(): Promise<string> {
  const directory = await mkdtemp(join(tmpdir(), "mailer-build-"));

  return join(directory, "templates.ts");
}

const copy = {
  default: "en-GB",
  catalogs: join(fixtures, "locales"),
  values: { supportLink: '<a href="mailto:support@example.com">support@example.com</a>' },
};

async function run(options: { senders?: readonly string[] } = {}) {
  const out = await into();
  const result = await build({ letters: fixtures, out, copy, ...options });
  const module = await readFile(result.out, "utf8");
  const bodies = await readFile(result.bodiesOut, "utf8");

  return { result, module, bodies };
}

describe("build", () => {
  it("should treat a file with a header as a letter and one without as a partial", async () => {
    const { result } = await run();

    expect([result.letters, result.partials]).toEqual([
      ["booking", "feedback", "magic-code", "welcome"],
      ["layout"],
    ]);
  });

  it("should write the module and say that it did", async () => {
    const { result } = await run();

    expect(result).toMatchObject({ written: true, stale: true });
  });

  it("should write nothing the second time, because nothing changed", async () => {
    const out = await into();

    await build({ letters: fixtures, out, copy });
    const second = await build({ letters: fixtures, out, copy });

    expect(second).toMatchObject({ written: false, stale: false });
  });

  it("should report a stale file without writing it in check mode", async () => {
    const out = await into();

    await writeFile(out, "// out of date\n", "utf8");
    const result = await build({ letters: fixtures, out, copy, check: true });

    expect([result.stale, result.written, await readFile(out, "utf8")]).toEqual([
      true,
      false,
      "// out of date\n",
    ]);
  });
});

describe("the module it writes", () => {
  let module = "";

  beforeAll(async () => {
    module = (await run()).module;
  });

  it("should say it is generated and not to edit it", () => {
    expect(module.split("\n")[0]).toMatch(
      /^\/\/ Generated by the mailer build from .*Do not edit\.$/,
    );
  });

  it("should import defineTemplates and the bodies beside it", () => {
    expect(module).toContain('import { defineTemplates } from "@rapture-sh/mailer";');
    expect(module).toContain('import { bodies, copy } from "./templates.bodies";');
  });

  it("should read a field off a placeholder in the body", () => {
    expect(module).toContain('"magic-code": { addressed: "caller"; fields: { code: string } };');
  });

  it("should give a letter with no placeholders no fields", () => {
    expect(module).toContain('"welcome": { addressed: "caller"; fields: Record<never, never> };');
  });

  it("should mark a letter with an inbox as addressed by itself", () => {
    expect(module).toContain(
      '"feedback": { addressed: "inbox"; fields: { from: string; note: string } };',
    );
  });

  it("should read an each block as rows and an if block as optional", () => {
    expect(module).toContain(
      '"booking": { addressed: "caller"; fields: { activityName: string; currency: string; participants: number; startsAt: number | Date; tickets: readonly string[]; timezone: string; totalMinor: number; voucherCode?: string } };',
    );
  });

  it("should turn a subject with a placeholder into a function of the fields", () => {
    expect(module).toContain(
      // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source, not a literal
      "subject: (fields) => `Your booking for ${fields.activityName} is confirmed`,",
    );
  });

  it("should resolve a subject written as a copy key through t", () => {
    expect(module).toContain(
      'subject: (fields, { t }) => t("magic-code.subject", { code: fields.code }),',
    );
  });

  it("should carry the locales and the catalogs", () => {
    expect(module).toContain("export type Locale = keyof typeof copy.catalogs;");
    expect(module).toContain("defineTemplates<Letters, typeof copy>({");
  });

  it("should leave a subject with no placeholder as a string", () => {
    expect(module).toContain('subject: "Welcome to Acme",');
  });

  it("should carry the sender, the inbox and the reply-to field through", () => {
    expect(module).toContain('from: "auth",');
    expect(module).toContain('inbox: "feedback@example.com",');
    expect(module).toContain('replyToField: "from",');
  });

  it("should carry the sample through, so the preview cannot drift from the fields", () => {
    expect(module).toContain('code: "519204",');
  });

  it("should take each body from the compiled module beside it", () => {
    expect(module).toContain('html: bodies["magic-code"],');
  });

  it("should not carry the precompiler's output, or its suppression", () => {
    expect(module).not.toContain("@ts-nocheck");
    expect(module).not.toContain("runtime.template(");
  });
});

describe("the compiled bodies beside it", () => {
  let bodies = "";

  beforeAll(async () => {
    bodies = (await run()).bodies;
  });

  it("should carry the suppression, because a precompiled body cannot pass strict mode", () => {
    expect(bodies.split("\n")[0]).toContain("@ts-nocheck");
  });

  it("should precompile every body rather than ship the source", () => {
    expect(bodies).toContain("runtime.template({");
    expect(bodies).not.toContain("{{#> layout");
  });

  it("should register the partials before any letter can use one", () => {
    expect(bodies.indexOf("registerPartial")).toBeLessThan(bodies.indexOf("export const bodies"));
  });
});

describe("what the build refuses", () => {
  it("should refuse a sender that is not declared", async () => {
    await expect(run({ senders: ["notifications"] })).rejects.toThrow(
      /from: 'auth' is not a sender/,
    );
  });

  it("should accept the senders the letters name", async () => {
    await expect(run({ senders: ["auth", "notifications"] })).resolves.toMatchObject({
      result: { written: true },
    });
  });

  it("should refuse a directory with no letters in it", async () => {
    const empty = await mkdtemp(join(tmpdir(), "mailer-empty-"));

    await expect(build({ letters: empty, out: join(empty, "out.ts") })).rejects.toThrow(
      /no letters found/,
    );
  });

  it("should name the file it could not read", async () => {
    const directory = await mkdtemp(join(tmpdir(), "mailer-bad-"));

    await writeFile(join(directory, "broken.hbs"), "---\nsubject: Hi\n", "utf8");

    await expect(build({ letters: directory, out: join(directory, "out.ts") })).rejects.toThrow(
      /broken\.hbs: the header opens with --- but never closes/,
    );
  });
});

describe("the module as a consumer gets it", () => {
  it("should be exactly what is committed under generated/", async () => {
    // The committed output is typechecked by tsc and rendered by generated.test.ts, so
    // this asserts three things at once: the output is reproducible, it compiles, and it
    // works. A fixture change rewrites it and fails once, the way a snapshot does.
    const result = await build({
      letters: fixtures,
      out: fileURLToPath(new URL("./generated/templates.ts", import.meta.url)),
      copy,
      senders: ["auth", "notifications"],
    });

    expect([result.written, result.stale]).toEqual([false, false]);
  });

  it("should report the keys no letter asked for", async () => {
    const { result } = await run();

    expect(result.unusedKeys).toEqual(["unused.key"]);
  });

  it("should report the locales it read", async () => {
    const { result } = await run();

    expect(result.locales).toEqual(["de-CH", "en-GB", "pirate-Speak"]);
  });
});
